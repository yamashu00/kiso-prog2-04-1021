// 【種類】確認（そのまま実行する）
// 【内容】変数でも、intのままだと割り算が切り捨てになることを確かめる。キャストすると小数になる
// 【まずやること】
//   ・実行する前に、2つのprintfの表示をペアで予想する
//   ・実行して、1行目が 3、2行目が 3.500000 になることを確認する
// 【やってみよう】
//   ① aとbの値を変えて、結果がどう変わるか予想してから実行する
//   ② (float)を b の方につけても、同じ結果になるか確かめる
// ==================================================
#include <stdio.h>

int main(void)
{
    int a = 11;
    int b = 2;

    printf("%d\n", a / b); //5.5
    printf("%f\n", a / (float)b); //5.5
    return 0;
}
