// 【内容】明るさの計算をキャストで書き直したもの。上限（255超え）のクランプはあるが、下限（0未満）のクランプはまだない
// 【まずやること】
//   ・実行して、c = 230 に 50 を足すと 255 にクランプされることを確認する
//   ・c の初期値や +50 の部分（例：+50 を -300 にするなど）を変えて、
//     下限（0未満）を下回るケースを自分で1つ作り、出力がおかしくなることを確認する
// 【やってみよう】
//   ① 0未満になった場合は「0」にクランプされるように、条件式を追加・修正する
//   ② 修正後、上限・下限どちらのケースでも正しくクランプされるか確認する
// ==================================================
#include <stdio.h>

int main(void)
{
    unsigned char c = 230;
    int v = (int)c + 50;
    /* intのまま0〜255に収めてからunsigned charに変換する。 */
    unsigned char out = (unsigned char)((v < 0) ? 0 : ((v > 255) ? 255 : v));

    printf("%d\n", out);

    v = (int)c - 300;  /* 230 - 300 = -70 → 下限の0 */
    out = (unsigned char)((v < 0) ? 0 : ((v > 255) ? 255 : v));
    printf("%d\n", out);

    v = (int)c - 30;  /* 230 - 30 = 200 → 範囲内なのでそのまま */
    out = (unsigned char)((v < 0) ? 0 : ((v > 255) ? 255 : v));
    printf("%d\n", out);
    return 0;
}
